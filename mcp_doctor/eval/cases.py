"""Reading and writing the eval case file.

Cases are a *committed artifact*, and that is the whole design. `--init` writes the file
once; a human reads it, deletes the cases that are wrong, and rewrites the ones that are
lazy; every run afterwards reads it unchanged. Nothing regenerates it silently, because a
suite that quietly rewrote itself would make two runs incomparable -- and comparing runs is
the only reason to have a score at all.

`--init` therefore refuses to overwrite an existing file without `--force`. That makes the
invariant structural rather than a thing to remember.

Drift is handled at two levels, because the two cases deserve different answers. A case
naming a tool that no longer exists cannot be run, so it is a usage error that names the
case and the tool. A tool surface that has merely *changed* -- a description edited, a
parameter added -- is a warning: the scores are no longer comparable to the last run, but
re-measuring after an edit is exactly what somebody is usually here to do.
"""

from __future__ import annotations

from collections import Counter
from collections.abc import Iterable
from pathlib import Path
from typing import Any

import yaml
from pydantic import ValidationError

from mcp_doctor.model import CaseKind, CaseSuite, EvalCase, ToolSpec

CASES_FILENAME = "mcp-doctor-cases.yaml"

# Wrapped at the same column as the code, so the generated file reads like the rest of the
# repo it lands in.
_WRAP = 88

_HEADER = """\
# mcp-doctor eval cases
#
# Generated by `mcp-doctor eval --init`, and yours from here on. Edit them: delete the
# prompts that do not sound like your users, and rewrite the ones that gave the answer
# away by borrowing the tool's own words. A generated suite is a starting point, not a
# benchmark.
#
# Committed on purpose. Scores are only comparable between runs over the same cases, so
# nothing regenerates this file unless you ask with --force.
#
#   kind: positive  one tool is clearly right
#         sibling   two tools plausibly fit and only one is correct -- the cases that
#                   actually separate a good server from a bad one
#         abstain   no tool should be called
"""


class CaseFileError(Exception):
    """The case file is missing, malformed, or no longer matches the server (exit code 2).

    Always names the file, and the case, and what to do -- a suite people cannot repair is
    worse than no suite.
    """


def default_cases_path(start: Path) -> Path:
    """Where cases live for a target rooted at `start`."""
    return start / CASES_FILENAME


def _require(value: Any, kind: type, *, what: str, path: Path) -> Any:
    if not isinstance(value, kind):
        raise CaseFileError(
            f"{path}: {what} should be {kind.__name__}, got {type(value).__name__}."
        )
    return value


def load_suite(path: Path) -> CaseSuite:
    """Read a case file, or explain precisely why it could not be read."""
    if not path.is_file():
        raise CaseFileError(
            f"No case file at {path}.\n"
            "  Generate one with:  mcp-doctor eval <target> --init\n"
            "  Then read it, edit it, and commit it."
        )
    try:
        raw = yaml.safe_load(path.read_text(encoding="utf-8"))
    except yaml.YAMLError as exc:
        raise CaseFileError(f"{path} is not valid YAML: {exc}") from exc
    except OSError as exc:
        raise CaseFileError(f"Could not read {path}: {exc}") from exc

    document = _require(raw or {}, dict, what="the document", path=path)
    entries = _require(document.get("cases") or [], list, what="'cases'", path=path)

    cases: list[EvalCase] = []
    for index, entry in enumerate(entries):
        _require(entry, dict, what=f"cases[{index}]", path=path)
        try:
            cases.append(EvalCase(**entry))
        except ValidationError as exc:
            label = entry.get("id") or f"cases[{index}]"
            raise CaseFileError(f"{path}: case {label} is not usable.\n  {_first(exc)}") from exc

    duplicates = [name for name, count in Counter(case.id for case in cases).items() if count > 1]
    if duplicates:
        raise CaseFileError(
            f"{path}: duplicate case ids: {', '.join(sorted(duplicates))}. "
            "Every case needs its own id -- they are how a failure is reported."
        )

    return CaseSuite(
        target=str(document.get("target") or ""),
        tool_digest=str(document.get("tool_digest") or ""),
        generated_with=document.get("generated_with") or None,
        cases=tuple(cases),
    )


def _first(exc: ValidationError) -> str:
    """The first validation complaint, in prose. Pydantic's full report is too much here."""
    errors = exc.errors()
    if not errors:  # pragma: no cover - pydantic always reports at least one
        return str(exc)
    first = errors[0]
    location = ".".join(str(part) for part in first.get("loc", ())) or "case"
    return f"{location}: {first.get('msg', 'is invalid')}"


def write_suite(path: Path, suite: CaseSuite, *, force: bool = False) -> None:
    """Write a case file, refusing to clobber one that already exists.

    The refusal is the point: an accidental regeneration silently discards every human edit
    in the file and makes the next score incomparable to the last, with nothing to show
    that anything happened.
    """
    if path.exists() and not force:
        raise CaseFileError(
            f"{path} already exists, and regenerating it would discard whatever you have "
            "edited into it.\n"
            "  Add --force if that is really what you want, or point --cases somewhere else."
        )

    body = {
        "target": suite.target,
        "tool_digest": suite.tool_digest,
        "generated_with": suite.generated_with,
        "cases": [_plain(case) for case in suite.cases],
    }
    rendered = yaml.safe_dump(
        body, sort_keys=False, default_flow_style=False, allow_unicode=True, width=_WRAP
    )
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(f"{_HEADER}\n{rendered}", encoding="utf-8")


def _plain(case: EvalCase) -> dict[str, Any]:
    """A case as ordered plain data.

    Written by hand rather than by `model_dump` so the field order is the reading order --
    what this case is, then what it expects, then the prompt. `None`s are dropped so an
    abstain case does not carry an `expected: null` line that only invites someone to fill
    it in.
    """
    entry: dict[str, Any] = {"id": case.id, "kind": case.kind.value}
    if case.expected is not None:
        entry["expected"] = case.expected
    if case.rival is not None:
        entry["rival"] = case.rival
    entry["prompt"] = case.prompt
    if case.note is not None:
        entry["note"] = case.note
    return entry


def validate_against(suite: CaseSuite, tools: Iterable[ToolSpec], *, path: Path) -> tuple[str, ...]:
    """Check a suite against the server's live tools. Returns warnings; raises on the fatal.

    Fatal is "this case cannot be run": it names a tool that is not there. Everything else
    is a warning, because a suite that is merely out of date is still a suite, and the
    person running it usually knows more about why than we do.
    """
    if not suite.cases:
        raise CaseFileError(
            f"{path} has no cases.\n"
            "  Regenerate with:  mcp-doctor eval <target> --init --force"
        )

    known = {tool.name for tool in tools}
    for case in suite.cases:
        for role, name in (("expected", case.expected), ("rival", case.rival)):
            if name is not None and name not in known:
                raise CaseFileError(
                    f"{path}: case {case.id} names {role} tool `{name}`, which this server "
                    "does not have.\n"
                    "  Fix the case, delete it, or regenerate the suite with "
                    "--init --force if the server has genuinely moved on."
                )

    warnings: list[str] = []
    covered = {case.expected for case in suite.cases if case.expected is not None}
    uncovered = sorted(known - covered)
    if uncovered:
        warnings.append(
            f"{len(uncovered)} tool(s) have no cases and are not being measured: "
            f"{', '.join(uncovered)}."
        )
    if not any(case.kind is CaseKind.ABSTAIN for case in suite.cases):
        warnings.append(
            "No abstain cases, so nothing checks whether the server knows when to stay "
            "out of the way."
        )
    return tuple(warnings)


def digest_warning(suite: CaseSuite, digest: str, *, path: Path) -> str | None:
    """A warning when the cases predate the server's current tools, or None."""
    if not suite.tool_digest or suite.tool_digest == digest:
        return None
    return (
        f"The tools have changed since {path.name} was generated "
        f"({suite.tool_digest} -> {digest}). The cases still run, but this score is not "
        "comparable to one taken before the change."
    )
